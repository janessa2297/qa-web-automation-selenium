package com.portfolio.orangehrm.tests;

import com.portfolio.orangehrm.base.BaseTest;
import com.portfolio.orangehrm.config.FrameworkConfig;
import com.portfolio.orangehrm.pages.DashboardPage;
import com.portfolio.orangehrm.pages.EmployeeListPage;
import java.util.UUID;
import org.testng.Assert;
import org.testng.SkipException;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.Test;

/**
 * Mutates data on the shared public demo. Not included in the default suite.
 * Run only after opting in with -Dallow.write.tests=true and the write-testng.xml suite.
 */
public class EmployeeLifecycleWriteTests extends BaseTest {

    @BeforeMethod(alwaysRun = true)
    public void requireExplicitOptIn() {
        if (!FrameworkConfig.writeTestsEnabled()) {
            throw new SkipException("Write tests disabled. Explicit opt-in required (see README)");
        }
    }

    @Test(groups = {"write", "e2e"}, description = "Create, find, and remove only the record created by this test")
    public void newEmployeeCanBeCreatedSearchedAndCleanedUp() {
        String suffix = UUID.randomUUID().toString().substring(0, 8);
        String firstName = "QAAuto";
        String lastName = "Demo" + suffix;
        String employeeId = null;
        boolean saveAttempted = false;

        DashboardPage dashboard = loginPage.loginSuccessfully(
            FrameworkConfig.username(), FrameworkConfig.password());
        EmployeeListPage employees = dashboard.openEmployeeList();

        try {
            var addEmployee = employees.openAddEmployee().enterEmployeeName(firstName, lastName);
            employeeId = addEmployee.generatedEmployeeId();
            Assert.assertNotNull(employeeId, "Employee ID should be generated by the app");
            Assert.assertFalse(employeeId.isBlank(), "Employee ID should not be blank");
            saveAttempted = true;
            addEmployee.save();

            employees = new DashboardPage(driver).openEmployeeList();
            employees.searchByEmployeeId(employeeId);
            Assert.assertTrue(employees.hasEmployee(employeeId, firstName, lastName),
                "New employee should appear in employee search results");
        } finally {
            if (saveAttempted && employeeId != null) {
                // Safe cleanup: delete only if record matches this test's generated name + ID.
                try {
                    employees = new DashboardPage(driver).openEmployeeList();
                    employees.searchByEmployeeId(employeeId);
                    employees.deleteCreatedEmployee(employeeId, firstName, lastName);
                } catch (RuntimeException cleanupFailure) {
                    System.err.println("WARNING: cleanup did not finish for test employee ID "
                        + employeeId + ": " + cleanupFailure.getMessage());
                }
            }
        }
    }
}
